// Cart state management (mock localStorage behavior)
export const getCartItems = () => {
  const items = localStorage.getItem('thalassery_cart');
  return items ? JSON.parse(items) : [];
};

export const addToCart = (item) => {
  const cart = getCartItems();
  const existingItem = cart.find(i => i.id === item.id);
  
  if (existingItem) {
    existingItem.quantity += 1;
  } else {
    cart.push({ ...item, quantity: 1 });
  }
  
  localStorage.setItem('thalassery_cart', JSON.stringify(cart));
  return cart;
};

export const updateCartQuantity = (itemId, quantity) => {
  const cart = getCartItems();
  const item = cart.find(i => i.id === itemId);
  
  if (item) {
    if (quantity <= 0) {
      const filtered = cart.filter(i => i.id !== itemId);
      localStorage.setItem('thalassery_cart', JSON.stringify(filtered));
      return filtered;
    }
    item.quantity = quantity;
    localStorage.setItem('thalassery_cart', JSON.stringify(cart));
  }
  
  return cart;
};

export const clearCart = () => {
  localStorage.removeItem('thalassery_cart');
  return [];
};

export const calculateTotal = (cart) => {
  return cart.reduce((total, item) => total + (item.price * item.quantity), 0);
};
